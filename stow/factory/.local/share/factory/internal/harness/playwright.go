package harness

import (
	"encoding/json"
	"fmt"
	"strings"
)

// MCPServer is an MCP server a browser role gets on top of the user's own.
type MCPServer struct {
	Name    string   `json:"-"`
	Command string   `json:"command"`
	Args    []string `json:"args"`
}

// Playwright is the one source of truth for the browser roles' MCP server.
// --isolated: browser roles that run side by side in one worktree would
// otherwise share, and fight over, one persistent browser profile.
var Playwright = MCPServer{
	Name:    "playwright",
	Command: "npx",
	Args:    []string{"-y", "@playwright/mcp@0.0.86", "--isolated", "--headless"},
}

// PlaywrightTools are the tools a browser role may call: builder-frontend's,
// then the two extra ones reviewer-ui uses.
var PlaywrightTools = func() []string {
	var out []string
	for _, t := range []string{
		"navigate", "snapshot", "take_screenshot", "resize", "click", "type", "press_key", "wait_for",
		"console_messages", "close", "hover", "emulate_media",
	} {
		out = append(out, "mcp__playwright__browser_"+t)
	}
	return out
}()

// claudeMCPConfig is the --mcp-config file: {"mcpServers":{"playwright":{…}}}.
func claudeMCPConfig(s MCPServer) ([]byte, error) {
	b, err := json.MarshalIndent(map[string]any{"mcpServers": map[string]MCPServer{s.Name: s}}, "", "  ")
	return append(b, '\n'), err
}

// piExtension is the -e file: a small pi extension that registers the server
// with direct exposure, so its tools are declared to the model.
func piExtension(s MCPServer) ([]byte, error) {
	name, err := json.Marshal(s.Name)
	if err != nil {
		return nil, err
	}
	spec, err := json.Marshal(map[string]any{"command": s.Command, "args": s.Args, "exposure": "direct"})
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by the factory for browser roles. Do not edit.\n")
	fmt.Fprintf(&b, "export default function (pi) {\n  pi.registerMcpServer(%s, %s)\n}\n", name, spec)
	return []byte(b.String()), nil
}
